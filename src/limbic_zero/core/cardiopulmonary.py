"""Cardiovascular Hemodynamics, Regional Blood Perfusion, and Pulmonary Gas/Acid-Base Physiology.

Grounded in Guyton & Hall Medical Physiology:
    - Sinoatrial node pacemaker modulated oppositely by sympathetic beta-1 tone
      (+chronotropy/+inotropy) and myelinated vagal muscarinic tone (-chronotropy),
      plus dorsal vagal bradycardic clamp under extreme inescapable shock.
    - Carotid sinus baroreceptor reflex buffering Mean Arterial Pressure (MAP).
    - Differential vasomotor routing of Cardiac Output across 4 vascular beds:
        1. Cerebral (autoregulated between MAP 60-150 mmHg, vasodilated by PaCO2!)
        2. Skeletal Muscle (vasoconstricted at rest, massively vasodilated by local
           metabolic adenosine/lactate + beta-2 epinephrine during exertion!)
        3. Splanchnic Gut/Liver (constricted strongly by alpha-1 sympathetic surge
           to divert blood to muscle & brain during emergencies!)
        4. Cutaneous Skin (regulated by hypothalamic thermoregulatory POAH drive
           to dump heat when hot, constricted by alpha-1 surge during cold/terror!)
    - Medullary respiratory center driven by retrotrapezoid PaCO2/pH chemoreceptors
      and carotid-body PaO2 hypoxic drive, coupled directly to ambient arena O2/CO2.
    - Bohr-shifted Hill oxyhemoglobin dissociation (SpO2) and Henderson-Hasselbalch
      arterial pH from PaCO2, plasma bicarbonate, and anaerobic lactate.
"""

from __future__ import annotations

from dataclasses import dataclass
import math


@dataclass
class CardiopulmonaryState:
    """Continuous state variables of the heart, vasculature, lungs, and arterial blood."""

    # Hemodynamics
    heart_rate_bpm: float = 72.0            # Beats per minute [30, 210]
    stroke_volume_ml: float = 70.0          # mL per beat [20, 125]
    mean_arterial_pressure_mmhg: float = 92.0  # mmHg [30, 190]
    blood_volume_fraction: float = 1.0      # Normalized plasma+RBC volume [0.55, 1.15] (dehydration lowers preload!)

    # Regional perfusion flows (L/min; healthy resting cardiac output ~5.0 L/min)
    cerebral_flow_lpm: float = 0.75         # Brain perfusion (~15% of resting CO)
    muscle_flow_lpm: float = 1.10           # Skeletal muscle perfusion (can surge >12 L/min in sprint!)
    splanchnic_flow_lpm: float = 1.40       # Gut/liver perfusion (drops sharply in sympathetic shock)
    cutaneous_flow_lpm: float = 0.45        # Skin thermoregulatory perfusion (0.05 to 3.5 L/min)
    renal_coronary_flow_lpm: float = 1.34   # Basal vital organ perfusion

    # Pulmonary mechanics & arterial blood gases
    resp_rate_bpm: float = 14.0             # Breaths per minute [4, 55]
    tidal_volume_l: float = 0.50            # Liters per breath [0.15, 2.8]
    pa_o2_mmhg: float = 96.0                # Arterial O2 partial pressure [15, 115] mmHg
    pa_co2_mmhg: float = 40.0               # Arterial CO2 partial pressure [18, 95] mmHg
    arterial_spo2: float = 0.975            # Oxyhemoglobin saturation [0.05, 1.0]
    plasma_bicarbonate_mmoll: float = 24.0  # HCO3- metabolic buffer [8, 36] mmol/L
    arterial_ph: float = 7.40               # Henderson-Hasselbalch blood pH [6.80, 7.65]

    # Ascending baroreceptor & chemoreceptor nerve firing rates [0, 1]
    carotid_baroreceptor_hz_norm: float = 0.50
    central_co2_chemoreceptor_drive: float = 0.08
    peripheral_hypoxic_drive: float = 0.02


@dataclass(frozen=True)
class CardiopulmonaryInputs:
    """Physiological couplings driving cardiopulmonary ODEs on each sub-step."""

    sympathetic_tone: float                 # [0, 1] thoracolumbar sympathetic outflow
    ventral_vagal_tone: float               # [0, 1] myelinated cardiovagal brake
    dorsal_vagal_tone: float                # [0, 1] unmyelinated freeze bradycardia
    plasma_epinephrine: float               # [0, 1] circulating adrenal epinephrine
    plasma_norepinephrine: float            # [0, 1] circulating norepinephrine
    beta_receptor_sensitivity: float        # [0.2, 1.2] receptor desensitization factor
    muscle_metabolic_vasodilator: float     # [0, 1] local adenosine/lactate/K+ hyperemia signal
    cutaneous_vasodilation_cmd: float       # [0, 1] hypothalamic POAH skin heat-dump signal
    cutaneous_vasoconstrict_cmd: float      # [0, 1] hypothalamic cold-defense signal
    whole_body_o2_consumption_ml_min: float # Total VO2 demanded by brain + muscle + viscera (mL O2/min)
    whole_body_co2_production_ml_min: float # Total VCO2 generated by aerobic + buffering (mL CO2/min)
    blood_lactate_mmoll: float              # Anaerobic lactic acid concentration [0.5, 25.0] mmol/L
    core_temp_celsius: float                # Body temperature shifting Hb-O2 curve (Bohr/temp effect)
    hydration_fraction: float               # [0.6, 1.1] body water determining plasma preload volume
    ambient_o2_kpa: float                   # Local arena atmospheric O2 partial pressure (~21.3 kPa normoxia)
    ambient_co2_kpa: float                  # Local arena atmospheric CO2 partial pressure (~0.04 kPa fresh air)


class CardiopulmonaryEngine:
    """Integrates coupled cardiovascular, regional perfusion, and blood-gas dynamics."""

    KPA_TO_MMHG: float = 7.50062

    @staticmethod
    def compute_spo2_hill_bohr(pa_o2_mmhg: float, ph: float, temp_c: float, pa_co2_mmhg: float) -> float:
        """Oxyhemoglobin dissociation curve with physiological Bohr (pH/CO2) and thermal shifts.

        Standard P50 is 26.8 mmHg at pH 7.40, PaCO2 40 mmHg, T 37.0 C.
        Acidosis, hypercapnia, and fever shift the curve RIGHT (higher P50), unloading O2
        into metabolically active tissues while lowering pulmonary saturation under hypoxia.
        """
        p50 = (
            26.8
            * (10.0 ** (0.40 * (7.40 - ph)))
            * (10.0 ** (0.06 * ((pa_co2_mmhg - 40.0) / 10.0)))
            * (10.0 ** (0.024 * (temp_c - 37.0)))
        )
        p50 = max(14.0, min(55.0, p50))
        po2 = max(1.0, pa_o2_mmhg)
        hill_n = 2.7
        num = po2 ** hill_n
        den = num + (p50 ** hill_n)
        return max(0.02, min(0.999, num / den))

    @staticmethod
    def compute_henderson_hasselbalch_ph(pa_co2_mmhg: float, hco3_mmoll: float) -> float:
        """Exact Henderson-Hasselbalch arterial pH = 6.1 + log10([HCO3-] / (0.03 * PaCO2))."""
        denom = max(0.3, 0.0301 * max(10.0, pa_co2_mmhg))
        ratio = max(0.5, hco3_mmoll) / denom
        ph = 6.10 + math.log10(ratio)
        return max(6.75, min(7.68, ph))

    def step(self, state: CardiopulmonaryState, inp: CardiopulmonaryInputs, dt: float) -> Tuple[float, float]:
        """Advance cardiopulmonary state by ``dt`` seconds.

        Returns:
            Tuple ``(o2_inhaled_mol_equiv, co2_exhaled_mol_equiv)`` exchanged with the
            local arena atmosphere cell for mass conservation.
        """
        # 1. Blood volume coupled to hydration (hypovolemia lowers venous preload)
        target_bv = max(0.58, min(1.12, 0.35 + 0.65 * inp.hydration_fraction))
        state.blood_volume_fraction += (target_bv - state.blood_volume_fraction) * min(1.0, dt * 0.5)

        # 2. Carotid sinus baroreceptor firing (sigmoidal around 92 mmHg)
        state.carotid_baroreceptor_hz_norm = 1.0 / (
            1.0 + math.exp(-(state.mean_arterial_pressure_mmhg - 92.0) / 16.0)
        )
        baro_reflex_brake = state.carotid_baroreceptor_hz_norm - 0.50  # >0 when hypertensive, <0 when hypotensive

        # 3. Sinoatrial Heart Rate dynamics (intrinsic pacemaker ~100 bpm with vagal brake & beta-1 drive)
        beta_drive = (0.65 * inp.sympathetic_tone + 0.55 * inp.plasma_epinephrine) * inp.beta_receptor_sensitivity
        vagal_brake = 0.85 * inp.ventral_vagal_tone + 0.45 * max(0.0, baro_reflex_brake)
        hypovolemic_tachy = max(0.0, 1.0 - state.blood_volume_fraction) * 55.0
        fever_tachy = max(-10.0, (inp.core_temp_celsius - 37.0) * 8.5)  # ~8.5 bpm per +1 C fever (Liebermeister's rule!)
        dorsal_freeze_drop = 48.0 * (inp.dorsal_vagal_tone ** 1.6)

        target_hr = (
            96.0
            + 95.0 * beta_drive
            - 42.0 * vagal_brake
            + hypovolemic_tachy
            + fever_tachy
            - dorsal_freeze_drop
        )
        target_hr = max(32.0, min(208.0, target_hr))
        state.heart_rate_bpm += (target_hr - state.heart_rate_bpm) * min(1.0, dt / 1.4)

        # 4. Stroke Volume (Frank-Starling venous preload * beta-1 myocardial contractility - extreme tachycardia filling penalty)
        preload_factor = math.sqrt(max(0.3, state.blood_volume_fraction))
        muscle_pump_return = 1.0 + 0.28 * inp.muscle_metabolic_vasodilator
        inotropy = 1.0 + 0.42 * beta_drive - 0.25 * inp.dorsal_vagal_tone
        # Above 165 bpm, diastolic ventricular filling time shortens
        diastolic_filling_factor = 1.0 if state.heart_rate_bpm < 160.0 else max(
            0.62, 1.0 - 0.0065 * (state.heart_rate_bpm - 160.0)
        )
        acidosis_depression = max(0.45, 1.0 - max(0.0, 7.25 - state.arterial_ph) * 0.9)

        target_sv = 70.0 * preload_factor * muscle_pump_return * inotropy * diastolic_filling_factor * acidosis_depression
        target_sv = max(18.0, min(125.0, target_sv))
        state.stroke_volume_ml += (target_sv - state.stroke_volume_ml) * min(1.0, dt / 1.8)

        cardiac_output_lpm = (state.heart_rate_bpm * state.stroke_volume_ml) / 1000.0

        # 5. Regional Vascular Conductances & Systemic Vascular Resistance (Ohm's fluid law: Flow = MAP * Conductance)
        # Note: Central defense/sympathetic reaction overrides baroreflex inhibition on splanchnic beds!
        symp_vasomotor = max(0.0, min(1.6, 0.85 * (inp.sympathetic_tone ** 1.3) + 0.60 * inp.plasma_norepinephrine))
        alpha1_constrict = max(0.0, symp_vasomotor - 0.22 * baro_reflex_brake)

        # Cerebral vascular conductance: tight myogenic autoregulation + strong CO2 vasodilation!
        co2_cerebral_factor = 1.0 + 0.028 * max(-15.0, min(35.0, state.pa_co2_mmhg - 40.0))
        hypoxic_cerebral_boost = 1.0 + 0.65 * max(0.0, (60.0 - state.pa_o2_mmhg) / 45.0)
        eff_map_for_brain = max(25.0, state.mean_arterial_pressure_mmhg)
        autoreg_comp = 92.0 / max(55.0, min(145.0, eff_map_for_brain))
        g_brain = (0.75 / 92.0) * autoreg_comp * co2_cerebral_factor * hypoxic_cerebral_boost

        # Skeletal muscle conductance: local metabolic hyperemia + epinephrine beta-2 surges up to 10x!
        beta2_dilation = 1.35 * inp.plasma_epinephrine * inp.beta_receptor_sensitivity
        metabolic_hyperemia = 8.5 * (inp.muscle_metabolic_vasodilator ** 1.2)
        muscle_constrict = max(0.40, 1.0 - 0.35 * alpha1_constrict * (1.0 - 0.85 * inp.muscle_metabolic_vasodilator))
        g_muscle = (1.10 / 92.0) * muscle_constrict * (1.0 + beta2_dilation + metabolic_hyperemia)

        # Splanchnic gut/liver conductance: dense alpha-1 innervation clamps flow strongly in emergencies!
        splanchnic_clamp = 1.0 / (1.0 + 8.5 * (symp_vasomotor ** 1.4))
        vagal_digestive_boost = 0.85 + 0.35 * inp.ventral_vagal_tone
        g_splanchnic = (1.40 / 92.0) * splanchnic_clamp * vagal_digestive_boost

        # Cutaneous skin conductance: resting ~0.25 L/min, surging up to 3.2 L/min in heat stress
        skin_dilate = 1.0 + 11.5 * inp.cutaneous_vasodilation_cmd
        skin_blanch = 1.0 / (1.0 + 2.8 * inp.cutaneous_vasoconstrict_cmd + 1.8 * alpha1_constrict)
        g_cutaneous = (0.25 / 92.0) * skin_dilate * skin_blanch

        # Basal renal + coronary conductance (coronary dilates with heart workload)
        coronary_work_boost = 1.0 + 0.35 * max(0.0, (cardiac_output_lpm - 5.0) / 10.0)
        g_basal = (1.34 / 92.0) * coronary_work_boost / (1.0 + 0.45 * alpha1_constrict)

        total_conductance = max(1e-3, g_brain + g_muscle + g_splanchnic + g_cutaneous + g_basal)

        # Arterial pressure follows Cardiac Output / Total Vascular Conductance (Windkessel arterial compliance)
        target_map = cardiac_output_lpm / total_conductance
        target_map = max(25.0, min(195.0, target_map))
        state.mean_arterial_pressure_mmhg += (target_map - state.mean_arterial_pressure_mmhg) * min(1.0, dt / 1.1)

        # Distribute actual cardiac output across regional beds proportionally to conductance
        state.cerebral_flow_lpm = cardiac_output_lpm * (g_brain / total_conductance)
        state.muscle_flow_lpm = cardiac_output_lpm * (g_muscle / total_conductance)
        state.splanchnic_flow_lpm = cardiac_output_lpm * (g_splanchnic / total_conductance)
        state.cutaneous_flow_lpm = cardiac_output_lpm * (g_cutaneous / total_conductance)
        state.renal_coronary_flow_lpm = cardiac_output_lpm * (g_basal / total_conductance)

        # 6. Chemoreceptor Respiratory Drive & Alveolar Ventilation
        # Retrotrapezoid nucleus responds sharply to PaCO2 > 40 mmHg and arterial acidosis (pH < 7.38)
        co2_excess = max(0.0, state.pa_co2_mmhg - 38.0)
        acid_excess = max(0.0, 7.39 - state.arterial_ph) * 45.0  # Kussmaul compensatory hyperventilation in acidosis!
        state.central_co2_chemoreceptor_drive = math.tanh((co2_excess * 0.065) + (acid_excess * 0.08))

        # Carotid body glomus cells fire exponentially when PaO2 drops below ~65 mmHg
        hypoxia_gap = max(0.0, 75.0 - state.pa_o2_mmhg)
        state.peripheral_hypoxic_drive = math.tanh((hypoxia_gap / 32.0) ** 2)

        ventilatory_drive = (
            2.2 * state.central_co2_chemoreceptor_drive
            + 1.8 * state.peripheral_hypoxic_drive
            + 0.85 * inp.muscle_metabolic_vasodilator  # Central command exercise hyperpnea!
            + 0.35 * inp.sympathetic_tone
        )
        target_rr = max(6.0, min(52.0, 12.0 + 28.0 * math.tanh(ventilatory_drive * 0.75)))
        target_vt = max(0.22, min(2.4, 0.45 + 1.20 * math.tanh(ventilatory_drive * 0.65)))

        state.resp_rate_bpm += (target_rr - state.resp_rate_bpm) * min(1.0, dt / 1.5)
        state.tidal_volume_l += (target_vt - state.tidal_volume_l) * min(1.0, dt / 1.5)

        # Alveolar ventilation (subtracting ~0.15 L anatomical dead space per breath)
        effective_vt = max(0.05, state.tidal_volume_l - 0.15)
        alveolar_vent_lpm = state.resp_rate_bpm * effective_vt

        # 7. Alveolar-Arterial O2 & CO2 Gas Exchange coupled to Ambient Arena Atmosphere
        inspired_po2_mmhg = max(5.0, inp.ambient_o2_kpa * self.KPA_TO_MMHG * 0.938)  # Humidified tracheal PO2
        inspired_pco2_mmhg = max(0.0, inp.ambient_co2_kpa * self.KPA_TO_MMHG)

        # Standard physiological alveolar gas equations (863 mmHg*L/mL STPD->BTPS factor)
        vent_safe = max(0.6, alveolar_vent_lpm)
        target_pa_co2 = inspired_pco2_mmhg + (0.863 * inp.whole_body_co2_production_ml_min) / vent_safe
        target_pa_co2 = max(16.0, min(105.0, target_pa_co2))

        rq = max(0.7, min(1.2, inp.whole_body_co2_production_ml_min / max(50.0, inp.whole_body_o2_consumption_ml_min)))
        alveolar_po2 = inspired_po2_mmhg - ((target_pa_co2 - inspired_pco2_mmhg) / rq)
        # Small physiological A-a gradient (~4 mmHg), widening only if cardiac perfusion collapses
        aa_gradient = 4.0 + max(0.0, (55.0 - state.mean_arterial_pressure_mmhg) * 0.25)
        target_pa_o2 = max(12.0, min(115.0, alveolar_po2 - aa_gradient))

        # Lung & arterial blood gas washout time constant (~3.2s, faster during hyperventilation)
        gas_tau = max(0.9, 3.8 / (0.5 + 0.16 * vent_safe))
        state.pa_co2_mmhg += (target_pa_co2 - state.pa_co2_mmhg) * min(1.0, dt / gas_tau)
        state.pa_o2_mmhg += (target_pa_o2 - state.pa_o2_mmhg) * min(1.0, dt / gas_tau)

        # 8. Bicarbonate buffering of lactic acid & Henderson-Hasselbalch arterial pH
        # Rising blood lactate above resting 1.0 mmol/L titrates HCO3- 1:1 via lactic acidosis buffering
        excess_lactate = max(0.0, inp.blood_lactate_mmoll - 1.0)
        target_hco3 = max(7.0, 24.2 - 0.85 * excess_lactate)
        state.plasma_bicarbonate_mmoll += (target_hco3 - state.plasma_bicarbonate_mmoll) * min(1.0, dt / 3.0)

        state.arterial_ph = self.compute_henderson_hasselbalch_ph(
            state.pa_co2_mmhg, state.plasma_bicarbonate_mmoll
        )
        state.arterial_spo2 = self.compute_spo2_hill_bohr(
            state.pa_o2_mmhg, state.arterial_ph, inp.core_temp_celsius, state.pa_co2_mmhg
        )

        # Return actual gas mass exchanged over dt (in liters STPD) for world atmosphere conservation
        o2_consumed_liters = (inp.whole_body_o2_consumption_ml_min / 1000.0) * (dt / 60.0)
        co2_exhaled_liters = (inp.whole_body_co2_production_ml_min / 1000.0) * (dt / 60.0)
        return o2_consumed_liters, co2_exhaled_liters
